"""
Reads the breakthrough export from the game log (written by ExportBreakthroughs.lua)
and generates webapp/src/data/breakthroughDescriptions.ts.

Note: this replaces the current file, including the notes taken from the wiki.

Usage:  python log2breakthroughs.py [path/to/data.log]
"""

import json
import os
import re
import sys

input_txt_file = sys.argv[1] if len(sys.argv) > 1 else "data.log"
here = os.path.dirname(os.path.abspath(__file__))
output_ts_file = os.path.join(here, "..", "webapp", "src", "data", "breakthroughDescriptions.ts")
breakthrough_list_file = os.path.join(here, "..", "webapp", "src", "helper", "TechBreakthroughList.ts")

START = "================== BREAKTHROUGHS START =================="
END = "================== BREAKTHROUGHS END =================="


def clean(text):
    """Turns the game's rich text into plain text."""
    text = re.sub(r"<newline>|<vspace[^>]*>", " ", text, flags=re.IGNORECASE)
    text = re.sub(r"<image [^>]*>", "", text, flags=re.IGNORECASE)
    # Formatting tags such as <em>, </em>, <color ...>, </color>, <green>
    text = re.sub(r"</?(em|color|green|red|yellow|white|left|right|center|style|tags)\b[^>]*>", "", text, flags=re.IGNORECASE)
    return re.sub(r"\s+", " ", text).strip()


def main():
    with open(input_txt_file, "r", encoding="utf-8") as file:
        lines = [line.rstrip("\n") for line in file]

    try:
        start = max(i for i, line in enumerate(lines) if line.strip() == START)
    except ValueError:
        sys.exit(f"No breakthrough export found in {input_txt_file}")

    descriptions = {}
    for line in lines[start + 1:]:
        if line.strip() == END:
            break
        parts = line.split("\t")
        if len(parts) != 3:
            print(f"Skipping malformed line: {line!r}")
            continue
        tech_id, _name, description = parts
        descriptions[tech_id.strip()] = clean(description)

    # Cross-check against the ids the web app uses
    with open(breakthrough_list_file, "r", encoding="utf-8") as file:
        known_ids = set(re.findall(r"['\"]([^'\"]+)['\"]", file.read()))
    missing = sorted(known_ids - descriptions.keys())
    extra = sorted(descriptions.keys() - known_ids)
    unresolved = sorted(k for k, v in descriptions.items() if re.search(r"<[^>]+>", v))

    entries = {k: {"description": v} for k, v in sorted(descriptions.items())}
    body = json.dumps(entries, indent=2, ensure_ascii=False)
    header = (
        "// What each breakthrough does, keyed by tech id (as in TechBreakthroughList).\n"
        "//\n"
        "// Generated by Data-extraction/log2breakthroughs.py from the in-game export\n"
        "// (Data-extraction/ExportBreakthroughs.lua). Re-run those to update.\n\n"
        "export interface BreakthroughInfo {\n"
        "  description: string;\n"
        "  /** Extra details, shown smaller below the description */\n"
        "  notes?: string[];\n"
        "}\n\n"
    )
    footer = (
        "\n\nexport function getBreakthroughInfo(id: string): BreakthroughInfo | undefined {\n"
        "  return BreakthroughDescriptions[id];\n"
        "}\n"
    )
    with open(output_ts_file, "w", encoding="utf-8", newline="\n") as file:
        file.write(header)
        file.write(f"export const BreakthroughDescriptions: Record<string, BreakthroughInfo> = {body};")
        file.write(footer)

    print(f"Wrote {len(descriptions)} descriptions to {os.path.normpath(output_ts_file)}")
    if missing:
        print(f"No description for {len(missing)} ids used by the web app: {', '.join(missing)}")
    if extra:
        print(f"Exported but not used by the web app: {', '.join(extra)}")
    if unresolved:
        print(f"Still contain <placeholders> (check the translation context in the Lua script): {', '.join(unresolved)}")


if __name__ == "__main__":
    main()
